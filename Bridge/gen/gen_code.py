#!/usr/bin/env python3
"""Emits the bridge's C tables and thunks from gen_bridge.py output.

  generated/bridge_tables.h   interface descriptors + native (SysV) call shapes, shared
  generated/pe_thunks.h       typed Win64 thunks per (PE shape, Windows slot)
  generated/callbacks.h       Win64 <-> macOS callback struct conversion table

usage: gen_code.py <generator output dir> <bridge/generated dir>
"""
import json
import os
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
interfaces = json.load(open(f"{src}/interfaces.json"))
structs = json.load(open(f"{src}/structs.json"))


def sdk_key(v):
    m = re.match(r"(\d+)([a-z]?)", v)
    return int(m.group(1)) * 10 + (ord(m.group(2)) - 96 if m.group(2) else 0)


# ---- shapes ------------------------------------------------------------------------

def pe_token(k):
    return k if k in ("f", "d") else "i"           # MSVC: everything but float/double uses GPRs


def pe_ret(k):
    if k in ("v", "f", "d"):
        return k
    if k in ("steamid", "gameid") or k.startswith("struct"):
        return "p"                                   # MSVC member functions return classes via hidden pointer
    return "i"


def struct_elements(name, sdk, size):
    """SysV classification check for a by-value struct; returns ffi byte-array size."""
    cands = [v for v in structs.values() if v["name"] == name and sdk_key(v["sdk"]) <= sdk_key(sdk)]
    if size <= 16 and cands:
        lay = max(cands, key=lambda v: sdk_key(v["sdk"]))["mac"]
        for eb in range(0, size, 8):
            kinds = [f["type"] for f in lay["fields"] if eb <= f["offset"] < eb + 8]
            if kinds and all(t in ("float", "double") for t in kinds):
                raise SystemExit(f"{name}: all-float eightbyte would be SSE class; byte array is wrong")
    return size


def mac_token(k, sdk):
    if k in ("i", "steamid"):
        return "i"
    if k in ("v", "f", "d"):
        return k
    if k == "gameid":
        return "g"                                   # non-trivially-copyable: by reference / sret
    if k == "fnptr":
        return "n"                                   # Windows callback pointer: not forwarded yet
    if k.startswith("struct"):
        size, name = k[6:].split(":")
        return f"s{struct_elements(name, sdk, int(size))}"
    raise SystemExit(f"unknown kind {k}")


pe_shapes, mac_shapes = {}, {}
iface_rows = []
for version in sorted(interfaces):
    info = interfaces[version]
    rows = []
    for e in info["methods"]:
        wr, wp = e["win"]
        mr, mp = e["mac"]
        pe = "".join(pe_token(k) for k in wp) + ":" + pe_ret(wr)
        mac = ",".join(mac_token(k, info["sdk"]) for k in mp) + ":" + mac_token(mr, info["sdk"])
        pe_id = pe_shapes.setdefault(pe, len(pe_shapes))
        mac_id = mac_shapes.setdefault(mac, len(mac_shapes))
        flags = 1 if e["name"] == "GetAPICallResult" else 0
        rows.append((e["native_slot"] if e["native_slot"] is not None else 0xFFFF, pe_id, mac_id, flags, e["name"]))
    iface_rows.append((version, info["sdk"], rows))

os.makedirs(dst, exist_ok=True)
H = "/* Generated by bridge/gen/gen_code.py from Steamworks SDK headers. Do not edit. */\n#pragma once\n#include <stdint.h>\n\n"

with open(f"{dst}/bridge_tables.h", "w") as f:
    f.write(H)
    f.write("#define METHOD_CALLRESULT 1   /* ISteam*Utils::GetAPICallResult: convert result struct */\n\n")
    f.write("struct method_desc { uint16_t native_slot, pe_shape, mac_shape, flags; };\n")
    f.write("struct iface_desc { const char *version; uint16_t sdk, count; const struct method_desc *methods; };\n\n")
    f.write("/* Native SysV shapes: comma-separated params, ':' return.\n"
            " * i int/pointer/CSteamID, f float, d double, g CGameID (by reference / sret),\n"
            " * n callback pointer (passed as NULL), sN by-value struct of N bytes. */\n")
    f.write(f"#define MAC_SHAPE_COUNT {len(mac_shapes)}\n")
    f.write("static const char *const mac_shapes[MAC_SHAPE_COUNT] = {\n")
    for s, i in sorted(mac_shapes.items(), key=lambda x: x[1]):
        f.write(f'    "{s}",\n')
    f.write("};\n\n#ifdef BRIDGE_PE\n")
    for n, (version, sdk, rows) in enumerate(iface_rows):
        f.write(f"static const struct method_desc m{n}[] = {{ /* {version} */\n")
        for slot, pe, mac, flags, name in rows:
            f.write(f"    {{ {slot}, {pe}, {mac}, {flags} }}, /* {name} */\n")
        f.write("};\n")
    f.write(f"\n#define IFACE_COUNT {len(iface_rows)}\n")
    f.write("static const struct iface_desc ifaces[IFACE_COUNT] = { /* sorted by version */\n")
    for n, (version, sdk, rows) in enumerate(iface_rows):
        f.write(f'    {{ "{version}", {sdk_key(sdk)}, {len(rows)}, m{n} }},\n')
    f.write("};\n#endif\n")

# ---- PE thunks --------------------------------------------------------------------------
used = {}
for version, sdk, rows in iface_rows:
    for win_slot, (slot, pe, mac, flags, name) in enumerate(rows):
        used.setdefault(pe, set()).add(win_slot)

CTYPE = {"i": "u64", "f": "float", "d": "double"}
with open(f"{dst}/pe_thunks.h", "w") as f:
    f.write(H)
    f.write("/* Each thunk captures its Win64 arguments with the right C types (floats arrive in\n"
            " * XMM registers), stores them as 64-bit bit patterns and calls pe_dispatch. */\n")
    f.write(f"#define PE_SHAPE_COUNT {len(pe_shapes)}\n")
    max_slot = max(max(s) for s in used.values()) + 1
    f.write(f"#define PE_MAX_SLOT {max_slot}\n\n")
    for shape, sid in sorted(pe_shapes.items(), key=lambda x: x[1]):
        params, ret = shape.split(":")
        for slot in sorted(used.get(sid, ())):
            args = ", ".join(f"{CTYPE[t]} a{k}" for k, t in enumerate(params))
            pack = ", ".join({"i": f"a{k}", "f": f"f2b(a{k})", "d": f"d2b(a{k})"}[t] for k, t in enumerate(params))
            body = f"u64 a[16] = {{ {pack} }}; (void)a;" if params else "u64 a[16] = { 0 };"
            name = f"th_{sid}_{slot}"
            if ret == "p":
                sig = f"static void *{name}(struct proxy *s, void *ret{', ' + args if args else ''})"
                f.write(f"{sig} {{ {body} pe_dispatch(s, {slot}, a, ret); return ret; }}\n")
            elif ret == "f":
                f.write(f"static float {name}(struct proxy *s{', ' + args if args else ''}) {{ {body} return b2f(pe_dispatch(s, {slot}, a, 0)); }}\n")
            elif ret == "d":
                f.write(f"static double {name}(struct proxy *s{', ' + args if args else ''}) {{ {body} return b2d(pe_dispatch(s, {slot}, a, 0)); }}\n")
            else:
                rt = "void" if ret == "v" else "u64"
                call = f"pe_dispatch(s, {slot}, a, 0)"
                f.write(f"static {rt} {name}(struct proxy *s{', ' + args if args else ''}) {{ {body} {'return ' if rt != 'void' else ''}{call}; }}\n")
        f.write("\n")
    for shape, sid in sorted(pe_shapes.items(), key=lambda x: x[1]):
        slots = sorted(used.get(sid, ()))
        f.write(f"static void *const th_table_{sid}[PE_MAX_SLOT] = {{ ")
        f.write(", ".join(f"[{s}] = (void *)th_{sid}_{s}" for s in slots))
        f.write(" };\n")
    f.write("static void *const *const th_tables[PE_SHAPE_COUNT] = { ")
    f.write(", ".join(f"th_table_{sid}" for sid in range(len(pe_shapes))))
    f.write(" };\n")

# ---- callbacks ---------------------------------------------------------------------------------
rows, fields = [], []
for v in sorted(structs.values(), key=lambda v: (v["callback"] or 0, -sdk_key(v["sdk"]))):
    if v["callback"] is None or not v["differs"]:
        continue
    w, m = v["win"], v["mac"]
    start = len(fields)
    for a, b in zip(w["fields"], m["fields"]):
        fields.append((a["offset"], b["offset"], min(a["size"], b["size"])))
    rows.append((v["callback"], sdk_key(v["sdk"]), w["size"], m["size"], start, len(fields) - start, v["name"]))
# collapse identical consecutive layouts of the same callback across SDK versions
dedup = []
for r in rows:
    if dedup and dedup[-1][0] == r[0] and dedup[-1][2:4] == r[2:4] and \
            fields[dedup[-1][4]:dedup[-1][4] + dedup[-1][5]] == fields[r[4]:r[4] + r[5]]:
        dedup[-1] = (r[0], r[1]) + dedup[-1][2:]       # keep the oldest SDK that has this layout
        continue
    dedup.append(r)
with open(f"{dst}/callbacks.h", "w") as f:
    f.write(H)
    f.write("struct cb_field { uint16_t win_off, mac_off, size; };\n")
    f.write("struct cb_layout { int32_t id; uint16_t min_sdk, win_size, mac_size; uint32_t first, count; };\n")
    f.write(f"#define CB_FIELD_COUNT {len(fields)}\nstatic const struct cb_field cb_fields[CB_FIELD_COUNT] = {{\n")
    for a, b, s in fields:
        f.write(f"    {{ {a}, {b}, {s} }},\n")
    f.write("};\n")
    f.write(f"#define CB_LAYOUT_COUNT {len(dedup)}\n/* sorted by id, then newest SDK first */\n")
    f.write("static const struct cb_layout cb_layouts[CB_LAYOUT_COUNT] = {\n")
    for r in dedup:
        f.write(f"    {{ {r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]} }}, /* {r[6]} */\n")
    f.write("};\n")

print(f"{len(iface_rows)} interfaces, {len(pe_shapes)} PE shapes, {len(mac_shapes)} native shapes, "
      f"{sum(len(s) for s in used.values())} thunks, {len(dedup)} callback layouts")
